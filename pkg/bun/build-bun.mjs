// Builds the Bun client into the package at dist/bun. Not the host.
// index.d.ts is generated from tsc output. It is not a source file.
import { execSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, normalize, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../..");
const out = join(here, "../dist/bun");
const gen = join(out, ".gen");
const webDist = join(here, "../dist/web");

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

execSync(
  "bun build --target bun --format esm --outfile pkg/dist/bun/index.mjs --external bun:sqlite --minify --define DIP_CLI_DUMP=false bun/src/client/pkg.ts",
  { cwd: repo, stdio: "inherit" },
);

execSync("tsc --project tsconfig-bun.json", { cwd: here, stdio: "inherit" });
await writeFile(join(out, "index.d.ts"), rollupDts(gen, webDist));
await rm(gen, { recursive: true, force: true });

// rollupDts turns the tsc graph into one dist/bun/index.d.ts.
// Web types point at dist/web, the same files the web entry uses.
function rollupDts(genRoot, webRoot) {
  const pkgDts = join(genRoot, "bun/src/client/pkg.d.ts");
  const pub = publicExports(readFileSync(pkgDts, "utf8"));
  const files = localClosure(genRoot, pkgDts);
  const imports = new Map();
  const parts = [];
  for (const file of files) {
    const parsed = parseDts(readFileSync(file, "utf8"));
    for (const row of parsed.imports) {
      const spec = rewriteSpec(genRoot, webRoot, file, row.spec);
      if (spec === undefined) continue;
      const cur = imports.get(spec) ?? new Map();
      for (const name of row.names) {
        const prev = cur.get(name.name);
        cur.set(name.name, prev === false ? false : name.typeOnly);
      }
      imports.set(spec, cur);
    }
    for (const decl of parsed.decls) {
      const bare = decl.replace(/^export\s+/, "").replace(/;\s*$/, "").trim();
      if (bare === "{}") continue;
      const name = declName(decl);
      if (file.endsWith(`${sep}cli-prf.d.ts`) && (name === undefined || !pub.has(name))) continue;
      parts.push(pub.has(name) ? decl : unexport(decl));
    }
  }
  const lines = [
    "// Generated by pkg/bun/build-bun.mjs from bun/src/client/pkg.ts. Do not edit.",
    "",
  ];
  for (const [spec, names] of imports) {
    const bits = [...names].map(([name, typeOnly]) => typeOnly ? `type ${name}` : name);
    lines.push(`import { ${bits.join(", ")} } from "${spec}";`);
  }
  if (imports.size > 0) lines.push("");
  lines.push(parts.join("\n\n"));
  lines.push("");
  return lines.join("\n");
}

function publicExports(text) {
  const names = new Set();
  for (const block of text.matchAll(/export \{([^}]+)\}/g)) {
    for (const part of block[1].split(",")) {
      const bit = part.trim().replace(/^type\s+/, "");
      if (bit !== "") names.add(bit);
    }
  }
  return names;
}

function localClosure(genRoot, pkgDts) {
  const seen = new Set();
  const order = [];
  const visit = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const text = readFileSync(file, "utf8");
    const specs = parseDts(text).imports.map((row) => row.spec);
    for (const spec of text.matchAll(/from "([^"]+)"/g)) specs.push(spec[1]);
    for (const spec of specs) {
      const target = resolveLocal(genRoot, file, spec);
      if (target !== undefined) visit(target);
    }
    if (file !== pkgDts) order.push(file);
  };
  visit(pkgDts);
  return order;
}

function resolveLocal(genRoot, fromFile, spec) {
  if (!spec.startsWith(".")) return undefined;
  let target = normalize(join(dirname(fromFile), spec));
  if (target.endsWith(".ts")) target = target.slice(0, -3) + ".d.ts";
  else if (!target.endsWith(".d.ts")) target += ".d.ts";
  const rel = relative(genRoot, target).split(sep).join("/");
  if (rel.startsWith("web/src/") || rel.startsWith("shared/")) return undefined;
  return target;
}

function rewriteSpec(genRoot, webRoot, fromFile, spec) {
  if (!spec.startsWith(".")) return spec;
  let target = normalize(join(dirname(fromFile), spec));
  if (target.endsWith(".ts")) target = target.slice(0, -3) + ".d.ts";
  else if (!target.endsWith(".d.ts")) target += ".d.ts";
  const rel = relative(genRoot, target).split(sep).join("/");
  let webRel;
  if (rel.startsWith("web/src/")) webRel = rel.slice("web/src/".length);
  else if (rel.startsWith("shared/")) webRel = rel;
  else return undefined;
  if (webRel.endsWith(".d.ts")) webRel = webRel.slice(0, -5);
  const distFile = join(webRoot, webRel + ".d.ts");
  if (!existsSync(distFile)) {
    throw new Error(`bun types need ${distFile}. Build the web bundle first.`);
  }
  return "../web/" + webRel;
}

function parseDts(text) {
  const imports = [];
  const lines = text.split("\n");
  let i = 0;
  const importRe = /^import\s+(type\s+)?\{([^}]+)\}\s+from\s+"([^"]+)";\s*$/;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === "") {
      i++;
      continue;
    }
    const m = importRe.exec(line);
    if (m === null) break;
    const typeMod = m[1] !== undefined;
    const names = m[2].split(",").map((part) => {
      const bit = part.trim();
      const typeOnly = typeMod || bit.startsWith("type ");
      return { name: bit.replace(/^type\s+/, ""), typeOnly };
    }).filter((n) => n.name !== "");
    imports.push({ names, spec: m[3] });
    i++;
  }
  const decls = [];
  let buf = "";
  let depth = 0;
  const rest = lines.slice(i).join("\n");
  for (const ch of rest) {
    buf += ch;
    if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0 && /\b(class|interface)\s/.test(buf)) {
        const trimmed = buf.trim();
        if (trimmed !== "") decls.push(trimmed);
        buf = "";
      }
    } else if (ch === ";" && depth === 0) {
      const trimmed = buf.trim();
      if (trimmed !== "") decls.push(trimmed);
      buf = "";
    }
  }
  return { imports, decls };
}

function declName(stmt) {
  const m = /^(?:\/\*\*[\s\S]*?\*\/\s*)?(?:export\s+)?(?:declare\s+)?(?:async\s+)?(?:class|function|type|interface|const|enum)\s+([A-Za-z0-9_]+)/.exec(stmt.trim());
  return m === null ? undefined : m[1];
}

function unexport(stmt) {
  return stmt
    .replace(/^export\s+declare\s+/, "declare ")
    .replace(/^export\s+type\s+/, "type ")
    .replace(/^export\s+/, "");
}
